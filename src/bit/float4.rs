use core::hint::unreachable_unchecked;

macro_rules! match_f4_cvt {
    ($x:ident) => {
        match $x {
            0x0 => 0.0,
            0x1 => 0.5,
            0x2 => 1.0,
            0x3 => 1.5,
            0x4 => 2.0,
            0x5 => 3.0,
            0x6 => 4.0,
            0x7 => 6.0,
            0x8 => -0.0,
            0x9 => -0.5,
            0xA => -1.0,
            0xB => -1.5,
            0xC => -2.0,
            0xD => -3.0,
            0xE => -4.0,
            0xF => -6.0,
            _ => unsafe { unreachable_unchecked() },
        }
    };

    ($x:ident $cvt:path) => {
        match $x {
            0x0 => $cvt(0.0),
            0x1 => $cvt(0.5),
            0x2 => $cvt(1.0),
            0x3 => $cvt(1.5),
            0x4 => $cvt(2.0),
            0x5 => $cvt(3.0),
            0x6 => $cvt(4.0),
            0x7 => $cvt(6.0),
            0x8 => $cvt(-0.0),
            0x9 => $cvt(-0.5),
            0xA => $cvt(-1.0),
            0xB => $cvt(-1.5),
            0xC => $cvt(-2.0),
            0xD => $cvt(-3.0),
            0xE => $cvt(-4.0),
            0xF => $cvt(-6.0),
            _ => unsafe { unreachable_unchecked() },
        }
    };
}

#[inline(always)]
pub const unsafe fn to_f32(x: u8) -> f32 {
    match_f4_cvt!(x)
}

#[inline(always)]
pub const unsafe fn to_f64(x: u8) -> f64 {
    match_f4_cvt!(x)
}

#[inline(always)]
#[cfg(feature = "half")]
pub const unsafe fn to_f16(x: u8) -> half::f16 {
    match_f4_cvt!(x half::f16::from_f32_const)
}

