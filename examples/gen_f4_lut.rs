use float4::F4E2M1;
use std::{
    fs,
    fmt::Write,
    path::Path,
};

const VALUES: [F4E2M1; 16] = [
    F4E2M1::from_bits(0x0),
    F4E2M1::from_bits(0x1),
    F4E2M1::from_bits(0x2),
    F4E2M1::from_bits(0x3),
    F4E2M1::from_bits(0x4),
    F4E2M1::from_bits(0x5),
    F4E2M1::from_bits(0x6),
    F4E2M1::from_bits(0x7),
    F4E2M1::from_bits(0x8),
    F4E2M1::from_bits(0x9),
    F4E2M1::from_bits(0xA),
    F4E2M1::from_bits(0xB),
    F4E2M1::from_bits(0xC),
    F4E2M1::from_bits(0xD),
    F4E2M1::from_bits(0xE),
    F4E2M1::from_bits(0xF),
];

fn generate_lut(
    name: &str,
    op: impl Fn(f64, f64) -> f64,
) -> String {
    let mut out = String::new();

    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub const {name}: [u8; 256] = [").unwrap();

    for a in 0..16 {
        for b in 0..16 {
            let af = VALUES[a].to_f64();
            let bf = VALUES[b].to_f64();

            let result = F4E2M1::from_f64(op(af, bf));

            writeln!(
                out,
                "    0x{:X}, // (0x{a:X}, 0x{b:X})",
                result.to_bits(),
            ).unwrap();
        }
    }

    writeln!(out, "];").unwrap();

    out
}

fn main() -> std::io::Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let output = root.join("src/bit/f4_lut.rs");

    let mut file = String::new();

    file.push_str(
        "//! Generated FP4 E2M1 lookup tables.\n\
         //!\n\
         //! Generated from `float4::F4E2M1`.\n\
         //! DO NOT EDIT THIS FILE BY HAND.\n\
         //!\n\
         //! Indexing: `(a << 4) | b`.\n\n",
    );

    file.push_str(&generate_lut("LUT_ADD", |a, b| a + b));
    file.push_str(&generate_lut("LUT_SUB", |a, b| a - b));
    file.push_str(&generate_lut("LUT_MUL", |a, b| a * b));
    file.push_str(&generate_lut("LUT_DIV", |a, b| a / b));

    fs::write(output, file)
}
